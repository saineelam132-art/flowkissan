"""Collect the results files into ONE data file for the website:  python tools/export_site.py -> web/data/site_data.js

The website never contains typed numbers: every number it shows is read from this file, which is made
only from results/ (written by the twin), config/design.json, data/crops.json and data/season_calendar.json.
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
RES = ROOT / "results" / "live"
OUT = ROOT / "web" / "data" / "site_data.js"


def J(p):
    return json.loads(Path(p).read_text(encoding="utf-8"))


def main():
    from engine.config import load_config, load_crops
    cfg, crops = load_config(), load_crops()
    plan = J(RES / "season_plan.json")
    H = pd.read_csv(RES / ("hourly_live.csv" if (RES / "hourly_live.csv").exists() else "hourly_flowers.csv"), parse_dates=["time_ist"])
    r = lambda c, k=2: [None if pd.isna(x) else round(float(x), k) for x in H[c]]
    hourly = {"t0": str(H.time_ist.iloc[0]), "n": len(H), "T_out": r("T_out", 1), "RH_out": r("RH_out", 0), "T_room": r("T_room"), "RH_room": r("RH_room", 1),
              "ice": r("pcm_pct", 1), "T_sup": r("T_sup"), "T_ret": r("T_ret"), "P_pv": r("P_pv", 3), "P_grid": r("P_grid", 3), "P_comp": r("P_comp", 3),
              "run": r("running_h"), "grid": r("grid_on"), "v_ice": r("v_ice"), "kg": r("kg_inside", 1), "cop": r("cop"),
              "Q_air": r("Q_air", 3), "Q_ch": r("Q_ch", 3), "Q_ice_room": r("Q_pcm_room", 3), "P_sol": r("P_solar_used", 3)}
    for c_ in ("ghi", "wind", "is_forecast"):
        if c_ in H:
            hourly[c_] = r(c_, 1)
    hourly["n_actual"] = int((H["is_forecast"] == 0).sum()) if "is_forecast" in H else len(H)
    two = {}
    for tag, fn in (("ideal", "hourly_flowers_ideal.csv"), ("best", "hourly_flowers.csv")):
        Z = pd.read_csv(RES / fn, parse_dates=["time_ist"])
        z = lambda c, k=2: [None if pd.isna(x) else round(float(x), k) for x in Z[c]]
        two[tag] = {"t0": str(Z.time_ist.iloc[0]), "n": len(Z), "T_room": z("T_room"), "ice": z("pcm_pct", 1), "grid": z("grid_on"), "P_comp": z("P_comp", 3), "T_out": z("T_out", 1)}
    photos = J(ROOT / "web" / "assets" / "photos.json")["photos"]
    data = {
        "generated": pd.Timestamp.now("Asia/Kolkata").strftime("%Y-%m-%d %H:%M IST"),
        "project": cfg["project"],
        "flowers": J(RES / "flowers_2026.json"), "monthly": J(RES / "monthly_2026.json"), "holds": J(RES / "holds.json"),
        "humidity": J(RES / "humidity_options.json"), "reality": J(RES / "reality_check.json"), "night": J(RES / "night_limit.json"),
        "load": J(RES / "load_sweep.json"), "ice": J(RES / "ice_sweep.json"), "cost": J(RES / "cost_roi.json"),
        "compare": J(ROOT / "results" / "compare_old_vs_new.json"),
        "practice": J(RES / "practice.json"), "control": J(RES / "control.json"), "two": two, "pipe": J(RES / "pipe_pump.json"), "solar": J(RES / "solar_only.json"), "live": J(RES / "live_2026.json"),
        "plan": {k: v for k, v in plan.items() if k not in ("fills_full_year",)}, "fills": plan["fills_full_year"],
        "crops": {k: v for k, v in crops.items() if isinstance(v, dict) and v.get("kind") == "flower"},
        "blocked": crops["blocked_flowers"], "rules": crops["flower_rules"],
        "ice_hx": cfg["live_run"]["ice_hx"], "pcm": cfg["pcm"], "humidity_cfg": cfg["humidity"],
        "photos": {k: v for k, v in photos.items() if v.get("kind") == "commons"},
        "concept": sorted(p.stem for p in (ROOT / "web" / "assets" / "concept").glob("*.webp")),
        "flower_photos": {p.stem: f"assets/flowers/{p.name}" for p in sorted((ROOT / "web" / "assets" / "flowers").iterdir()) if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".webp")},
        "flower_credits": J(ROOT / "web" / "assets" / "flowers" / "credits.json"),
        "hourly": hourly,
        "phi_eval": J(RES / "phi_eval_2026.json") if (RES / "phi_eval_2026.json").exists() else None,
        "phi_design": J(RES / "phi_design.json") if (RES / "phi_design.json").exists() else None,
        "phi_cfg": {k: v for k, v in J(ROOT / "config" / "phi.json").items() if k in ("flag", "calibration", "cusum", "isolation", "watermark", "masking", "model_uncertainty", "truth_plant", "sensors", "hard_rules")},
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// generated by python tools/export_site.py from results/ (do not edit)\nwindow.KK = "
                   + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n", encoding="utf-8")
    print("wrote", OUT, round(OUT.stat().st_size / 1024), "kB")


if __name__ == "__main__":
    main()
